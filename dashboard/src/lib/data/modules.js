export function recordTitle(key, record) {
  if (!record) return "Untitled";
  const config = MODULES[key];
  const titleField = config?.titleKey;
  const value = (titleField && record[titleField]) || record.title || record.name || record.caption;
  return value || "Untitled";
}

export function recordStatus(key, record) {
  return record?.status || MODULES[key]?.statusOptions?.[0] || "—";
}